function BlurredStagger({ text, active }) {
  const container = {
    hidden: { opacity: 0 },
    show: { opacity: 1, transition: { staggerChildren: 0.02 } },
  };

  const word = {
    hidden: {},
    show: { transition: { staggerChildren: 0.012 } },
  };

  const letter = {
    hidden: { opacity: 0, filter: 'blur(10px)' },
    show: { opacity: 1, filter: 'blur(0px)' },
  };

  return (
    <motion.p
      variants={container}
      initial="hidden"
      animate={active ? 'show' : 'hidden'}
      aria-label={text}
      className="max-w-3xl text-sm sm:text-base leading-relaxed text-slate-400 break-words"
    >
      {text.split(' ').map((value, wordIndex) => (
        <motion.span
          key={`${value}-${wordIndex}`}
          variants={word}
          aria-hidden="true"
          className="inline-block whitespace-nowrap"
        >
          {value.split('').map((character, characterIndex) => (
            <motion.span
              key={characterIndex}
              variants={letter}
              transition={{ duration: 0.3 }}
              className="inline-block"
            >
              {character}
            </motion.span>
          ))}
          {'\u00A0'}
        </motion.span>
      ))}
    </motion.p>
  );
}

function FAQItem({ question, answer, isOpen, onToggle, answerId }) {
  return (
    <div className="border-b border-white/[0.14]">
      <button
        type="button"
        onClick={onToggle}
        aria-expanded={isOpen}
        aria-controls={answerId}
        className="group flex w-full cursor-pointer items-center justify-between gap-4 border-0 bg-transparent py-6 text-left font-[inherit]"
      >
        <span
          className={`text-base font-normal tracking-tight transition-colors sm:text-lg ${
            isOpen ? 'text-white' : 'text-slate-100 group-hover:text-white'
          }`}
        >
          {question}
        </span>
        <motion.span
          variants={{ open: { rotate: 180 }, closed: { rotate: 0 } }}
          animate={isOpen ? 'open' : 'closed'}
          transition={{ duration: 0.25 }}
          className={`shrink-0 transition-colors ${
            isOpen ? 'text-[#93b3ff]' : 'text-slate-300 group-hover:text-white'
          }`}
        >
          <ChevronDown className="h-5 w-5" strokeWidth={2} />
        </motion.span>
      </button>

      <motion.div
        id={answerId}
        aria-hidden={!isOpen}
        initial={false}
        animate={{
          height: isOpen ? 'auto' : 0,
          marginBottom: isOpen ? 24 : 0,
        }}
        transition={{ duration: 0.3, ease: 'easeInOut' }}
        className="overflow-hidden"
      >
        <BlurredStagger text={answer} active={isOpen} />
      </motion.div>
    </div>
  );
}

